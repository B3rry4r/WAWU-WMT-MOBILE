#!/usr/bin/env node
// Generates src/components/icon/icons.generated.ts: the Lucide icons the canvas
// uses, by the names the board generators (design/_gen/*.js) call them, imported
// from the installed lucide-react-native (latest). Shapes come from the package;
// only the names come from the canvas. A canvas name the package no longer has
// (Lucide 1.x dropped brand logos) comes from Simple Icons, the official brand
// marks Lucide points to, read from the installed `simple-icons` package; one
// in neither is listed in MISSING and fails the icon test. Run `npm run icons`.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '../..');
const gen = path.join(root, 'design/_gen');
const canvasLucide = fs.readFileSync(path.join(gen, 'lucide.min.js'), 'utf8');
const m = { exports: {} };
new Function('module', 'exports', canvasLucide)(m, m.exports);
const canvasIcons = m.exports.icons;

const pkgDir = path.join(root, 'node_modules/lucide-react-native');
const version = require(path.join(pkgDir, 'package.json')).version;
const index = fs.readFileSync(path.join(pkgDir, 'dist/esm/lucide-react-native.mjs'), 'utf8');
const exported = new Set([...index.matchAll(/as ([A-Za-z0-9]+)/g)].map((x) => x[1]));

const boards = fs
  .readdirSync(gen)
  .filter((f) => f.endsWith('.js') && f !== 'lucide.min.js')
  .map((f) => fs.readFileSync(path.join(gen, f), 'utf8'))
  .join('\n');
const names = new Set();
for (const hit of boards.matchAll(/['"]([A-Z][A-Za-z0-9]*)['"]/g)) if (canvasIcons[hit[1]]) names.add(hit[1]);
const sorted = [...names].sort();
const have = sorted.filter((n) => exported.has(n));
const si = require(path.join(root, 'node_modules/simple-icons'));
const siVersion = require(path.join(root, 'node_modules/simple-icons/package.json')).version;
const brands = {};
const missing = [];
for (const n of sorted.filter((x) => !exported.has(x))) {
  const mark = si[`si${n}`];
  if (mark) brands[n] = { title: mark.title, path: mark.path };
  else missing.push(n);
}

const out = [
  '// GENERATED by scripts/design/gen_icons.js. Do not edit. Run `npm run icons`.',
  `// The canvas's icon names, from lucide-react-native ${version}.`,
  '',
  `import {\n${have.map((n) => `  ${n},`).join('\n')}\n} from 'lucide-react-native';`,
  '',
  `export const LUCIDE_VERSION = '${version}';`,
  '',
  `export const icons = {\n${have.map((n) => `  ${n},`).join('\n')}\n};`,
  '',
  `/** Brand logos Lucide no longer ships, from simple-icons ${siVersion} (CC0). Filled marks. */`,
  `export const brands = ${JSON.stringify(brands, null, 2)} as const;`,
  '',
  '/** Canvas icons found in neither package. Must stay empty. */',
  `export const MISSING: readonly string[] = ${JSON.stringify(missing)};`,
  '',
  'export type BrandName = keyof typeof brands;',
  'export type IconName = keyof typeof icons | BrandName;',
  '',
];
fs.writeFileSync(path.join(root, 'src/components/icon/icons.generated.ts'), out.join('\n'));
console.log(`${have.length} icons from lucide-react-native ${version}; brands from simple-icons ${siVersion}: ${Object.keys(brands).join(', ') || 'none'}; missing: ${missing.join(', ') || 'none'}`);
